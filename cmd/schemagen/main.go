// Command schemagen writes internal/db/schema.sql: every migration listed in
// the journal, in order. sqlc reads it to type-check the queries.
package main

import (
	"fmt"
	"os"
	"strings"

	"github.com/denysovkos/migraine.club/internal/db"
	"github.com/denysovkos/migraine.club/migrations"
)

func main() {
	ms, err := db.ReadMigrations(migrations.FS)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var b strings.Builder
	b.WriteString("-- Code generated by cmd/schemagen from migrations/. DO NOT EDIT.\n")
	for _, m := range ms {
		fmt.Fprintf(&b, "\n-- %s\n", m.Tag)
		for _, stmt := range m.Statements {
			b.WriteString(strings.TrimSpace(stmt))
			b.WriteString("\n")
		}
	}
	out := "internal/db/schema.sql"
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
