// Command schemagen writes internal/db/schema.sql for sqlc.
//
// It migrates a scratch database with the real migrations and prints every
// table from the Postgres catalog. Reading the catalog (rather than the
// migration files) means DDL that sqlc cannot follow, such as renames inside
// DO blocks, is still reflected exactly.
//
// Needs TEST_DATABASE_URL (or DATABASE_URL) pointing at a server where the
// user may create databases.
package main

import (
	"context"
	"fmt"
	"net/url"
	"os"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/denysovkos/migraine.club/internal/db"
	"github.com/denysovkos/migraine.club/migrations"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "schemagen:", err)
		os.Exit(1)
	}
}

func withDB(raw, name string) string {
	u, _ := url.Parse(raw)
	u.Path = "/" + name
	return u.String()
}

func run() error {
	raw := os.Getenv("TEST_DATABASE_URL")
	if raw == "" {
		raw = os.Getenv("DATABASE_URL")
	}
	if raw == "" {
		return fmt.Errorf("set TEST_DATABASE_URL")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()

	name := fmt.Sprintf("mc_schemagen_%d", time.Now().UnixNano())
	admin, err := pgx.Connect(ctx, withDB(raw, "postgres"))
	if err != nil {
		return err
	}
	defer admin.Close(ctx)
	if _, err := admin.Exec(ctx, fmt.Sprintf(`CREATE DATABASE %q`, name)); err != nil {
		return err
	}
	defer func() {
		_, _ = admin.Exec(context.Background(), fmt.Sprintf(`DROP DATABASE IF EXISTS %q WITH (FORCE)`, name))
	}()

	pool, err := pgxpool.New(ctx, withDB(raw, name))
	if err != nil {
		return err
	}
	defer pool.Close()
	if _, err := db.Migrate(ctx, pool, migrations.FS); err != nil {
		return err
	}

	rows, err := pool.Query(ctx, `
		SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull
		FROM pg_attribute a
		JOIN pg_class c ON c.oid = a.attrelid
		JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = 'public' AND c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped
		ORDER BY c.relname, a.attnum`)
	if err != nil {
		return err
	}
	defer rows.Close()

	var b strings.Builder
	b.WriteString("-- Code generated by cmd/schemagen from the migrated database. DO NOT EDIT.\n")
	current := ""
	for rows.Next() {
		var table, col, typ string
		var notNull bool
		if err := rows.Scan(&table, &col, &typ, &notNull); err != nil {
			return err
		}
		if table != current {
			if current != "" {
				b.WriteString("\n);\n")
			}
			fmt.Fprintf(&b, "\nCREATE TABLE %q (\n", table)
			current = table
		} else {
			b.WriteString(",\n")
		}
		fmt.Fprintf(&b, "  %q %s", col, typ)
		if notNull {
			b.WriteString(" NOT NULL")
		}
	}
	if current != "" {
		b.WriteString("\n);\n")
	}
	if err := rows.Err(); err != nil {
		return err
	}
	return os.WriteFile("internal/db/schema.sql", []byte(b.String()), 0o644)
}
