#!/usr/bin/env python3
"""Extracts the static pieces of renderHtml.ts template literals into
internal/service/reports/html_pieces_gen.go, so the Go renderer reproduces
their whitespace byte for byte. Run: python3 scripts/gen-report-html.py"""
import json

SRC = 'src/services/reports/clinician/renderHtml.ts'
s = open(SRC).read()

def literal_at(start):
    """Parse the template literal whose opening backtick is at start."""
    assert s[start] == '`'
    pieces, exprs, cur, i = [], [], '', start + 1
    while True:
        c = s[i]
        if c == '\\':
            cur += s[i:i+2]; i += 2; continue
        if c == '`':
            pieces.append(cur); return pieces, exprs, i + 1
        if c == '$' and s[i+1] == '{':
            pieces.append(cur); cur = ''
            j, depth = i + 2, 1
            while depth:
                ch = s[j]
                if ch == '`':
                    _, _, j = literal_at(j); continue
                if ch == '{': depth += 1
                elif ch == '}': depth -= 1
                j += 1
            exprs.append(s[i+2:j-1]); i = j; continue
        cur += c; i += 1

def find(anchor, nth=0):
    idx = -1
    for _ in range(nth + 1):
        idx = s.index(anchor, idx + 1)
    return s.index('`', idx)

targets = {
    'appt': ("parts.push(`\n      <section class=\"section appt-hero\">", 0),
    'cover': ("parts.push(section('Cover',", 0),
    'summary': ("parts.push(section('Summary',", 0),
    'trends': ("parts.push(section('Trends',", 0),
    'attackPage': ("model.attacks.pages.map((page, idx) =>", 0),
    'attackRow': ("page.map(attack =>", 0),
    'medications': ("parts.push(section('Medications',", 0),
    'diary': ("parts.push(section('Diary',", 0),
    'insights': ("parts.push(section('Conservative insights',", 0),
    'cycle': ("parts.push(section('Cycle & hormones',", 0),
    'document': ("  return `\n<!doctype html>", 0),
}

out = ['// Code generated by scripts/gen-report-html.py from renderHtml.ts. DO NOT EDIT.', '', 'package reports', '']
for name, (anchor, nth) in targets.items():
    pieces, exprs, _ = literal_at(find(anchor, nth))
    out.append(f'// {name} expressions, in order:')
    for e in exprs:
        out.append('//   ' + ' '.join(e.split())[:150])
    out.append(f'var {name}Pieces = []string{{')
    for p in pieces:
        out.append('\t' + json.dumps(p.replace('\\`', '`')) + ',')
    out.append('}')
    out.append('')
open('internal/service/reports/html_pieces_gen.go', 'w').write('\n'.join(out))
