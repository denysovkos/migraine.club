/**
 * Writes internal/db/q/json_order_gen.go: a MarshalJSON for every sqlc model
 * that lists keys in the order Drizzle returned them (the order of columns in
 * src/models/Schema.ts), which can differ from the physical column order sqlc
 * follows. Run with `make gen`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { getTableColumns, getTableName, is } from 'drizzle-orm';
import { PgTable } from 'drizzle-orm/pg-core';

import * as schema from '../src/models/Schema';

// Find sqlc's struct for each table by its set of JSON tags: sqlc's own
// singularisation rules are not worth re-implementing.
const models = new Map<string, string>();
for (const m of readFileSync('internal/db/q/models.go', 'utf8').matchAll(/type (\w+) struct \{([\s\S]*?)\n\}/g)) {
  const tags = [...m[2]!.matchAll(/json:"([^"]+)"/g)].map(x => x[1]).sort().join(',');
  models.set(tags, m[1]!);
}
function structName(keys: string[]): string {
  const name = models.get([...keys].sort().join(','));
  if (!name) {
    throw new Error(`no sqlc model with fields ${keys.join(', ')}`);
  }
  return name;
}

const tables = Object.values(schema)
  .filter(t => is(t, PgTable))
  .map(t => ({
    name: getTableName(t as PgTable),
    keys: Object.keys(getTableColumns(t as PgTable)),
    onUpdate: Object.values(getTableColumns(t as PgTable)).filter((c: any) => c.onUpdateFn).map((c: any) => c.name as string),
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

let out = `// Code generated by scripts/gen-go-json-order.ts from src/models/Schema.ts. DO NOT EDIT.

package q

`;
for (const t of tables) {
  const name = structName(t.keys);
  out += `// MarshalJSON writes ${t.name} rows with Drizzle's key order.
func (m ${name}) MarshalJSON() ([]byte, error) {
\treturn marshalOrdered(m, []string{${t.keys.map(k => JSON.stringify(k)).join(', ')}})
}

`;
}
out += `func allModels() []any {\n\treturn []any{${tables.map(t => `${structName(t.keys)}{}`).join(', ')}}\n}\n`;
out += `\n// OnUpdateColumns lists, per table, the columns Drizzle refreshed on every\n// UPDATE ($onUpdate). Go queries must set them explicitly.\nvar OnUpdateColumns = map[string][]string{\n${tables.filter(t => t.onUpdate.length).map(t => `\t${JSON.stringify(t.name)}: {${t.onUpdate.map(c => JSON.stringify(c)).join(', ')}},`).join('\n')}\n}\n`;
writeFileSync('internal/db/q/json_order_gen.go', out);
